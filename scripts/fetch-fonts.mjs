/**
 * Vendors the three Kerdial typefaces (Gabarito, Manrope, JetBrains Mono) into
 * `web/public/fonts/` as self-hosted variable woff2, and regenerates
 * `web/src/styles/fonts.css` from what it downloaded.
 *
 * Self-hosting is not a preference here: `api/src/security-headers.ts` sets
 * `font-src 'self'`, so a Google Fonts CDN URL is blocked outright at runtime.
 * It also keeps the PWA's offline story intact — a cached shell that cannot
 * reach fonts.gstatic.com would otherwise render in a fallback face.
 *
 * Only the `latin` and `latin-ext` subsets are taken. The UI is French, and
 * `latin` alone misses the OE ligature; cyrillic/greek/vietnamese have no reader in this product.
 * Note that `latin` is also the subset carrying U+2212 MINUS SIGN, which the
 * design mandates over a hyphen for every negative figure.
 *
 * Run: `node scripts/fetch-fonts.mjs`
 */
import { mkdir, writeFile } from "node:fs/promises";
import { join } from "node:path";

const UA =
  "Mozilla/5.0 (X11; Linux x86_64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120.0 Safari/537.36";
const WANTED_SUBSETS = new Set(["latin", "latin-ext"]);
const OUT_DIR = join("web", "public", "fonts");
const CSS_OUT = join("web", "src", "styles", "fonts.css");

/** family: the Google Fonts family name; file: our local basename; axis: the wght range we ship. */
const FAMILIES = [
  { family: "Gabarito", file: "gabarito", axis: "400..800" },
  { family: "Manrope", file: "manrope", axis: "400..800" },
  { family: "JetBrains Mono", file: "jetbrains-mono", axis: "400..600" },
];

/** Splits a Google Fonts stylesheet into `{ subset, url, unicodeRange }` per @font-face block. */
function parseFaces(css) {
  const faces = [];
  const blocks = css.split("/*").slice(1);
  for (const block of blocks) {
    const subset = block.slice(0, block.indexOf("*/")).trim();
    const url = /src:\s*url\((https:\/\/[^)]+\.woff2)\)/.exec(block)?.[1];
    const range = /unicode-range:\s*([^;]+);/.exec(block)?.[1]?.trim();
    if (subset && url && range) faces.push({ subset, url, unicodeRange: range });
  }
  return faces;
}

await mkdir(OUT_DIR, { recursive: true });

const rules = [];
for (const { family, file, axis } of FAMILIES) {
  const query = `family=${family.replace(/ /g, "+")}:wght@${axis}&display=swap`;
  const res = await fetch(`https://fonts.googleapis.com/css2?${query}`, {
    headers: { "User-Agent": UA },
  });
  if (!res.ok) throw new Error(`${family}: stylesheet fetch failed with ${res.status}`);
  const faces = parseFaces(await res.text()).filter((f) => WANTED_SUBSETS.has(f.subset));
  if (faces.length !== WANTED_SUBSETS.size) {
    throw new Error(`${family}: expected ${WANTED_SUBSETS.size} subsets, got ${faces.length}`);
  }

  for (const face of faces) {
    const basename = `${file}-${face.subset}.woff2`;
    const font = await fetch(face.url, { headers: { "User-Agent": UA } });
    if (!font.ok) throw new Error(`${basename}: font fetch failed with ${font.status}`);
    const bytes = Buffer.from(await font.arrayBuffer());
    await writeFile(join(OUT_DIR, basename), bytes);
    console.log(`${basename}  ${(bytes.length / 1024).toFixed(1)} KiB`);

    const [min, max] = axis.split("..");
    rules.push(
      `/* ${family} — ${face.subset} */\n` +
        `@font-face {\n` +
        `  font-family: "${family}";\n` +
        `  font-style: normal;\n` +
        `  font-weight: ${min} ${max};\n` +
        `  font-display: swap;\n` +
        `  src: url("/fonts/${basename}") format("woff2");\n` +
        `  unicode-range: ${face.unicodeRange};\n` +
        `}`,
    );
  }
}

const header =
  `/* Generated by scripts/fetch-fonts.mjs — do not edit by hand.\n` +
  `   Self-hosted because api/src/security-headers.ts sets font-src 'self'.\n` +
  `   All three families are SIL Open Font License 1.1; see docs/licenses/fonts.md.\n` +
  `   Variable fonts: one file per subset covers the whole weight axis. */\n\n`;
await writeFile(CSS_OUT, `${header + rules.join("\n\n")}\n`);
console.log(`\nwrote ${CSS_OUT} (${rules.length} @font-face rules)`);
